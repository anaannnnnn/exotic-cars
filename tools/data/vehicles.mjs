/*
 * Curated list of generation-level vehicles, chosen because Dubai stockists list wheels / aero parts
 * specifically for them (see the fitment frequency report in tools/report.mjs).
 *
 *  id      stable slug
 *  match   regexes tested against the fitment text of a product title (upper-cased, text after " for ")
 *  ank     how to find the factory spec row(s) in the ANKUSI open dataset (make, model regex, year span)
 *  sf      how to find real 3D models on Sketchfab (query, must-match regex, preferred regex)
 *
 * Years: to = 0 means still in production.
 */
const rx = (s, f = 'i') => new RegExp(s, f);

function v(id, make, model, gen, from, to, body, country, match, ank, sf) {
  return { id, make, model, gen, from, to, body, country, match, ank, sf };
}

